/**
 * generate-asset-inventory.js
 *
 * src/assets/** 와 public/** 의 파일을 전부 걸어 다니며
 * src/data/assetInventory.js 를 생성한다. 스토리북 07 Assets 가 이 목록으로
 * 모든 이미지·영상·오디오·폰트를 빠짐없이 그린다.
 *
 * 항목: { path, root, folder, name, ext, kind, bytes, url, importKey }
 *  - url       : public/ 파일은 사이트 루트 기준 URL ("/images/a.jpg"). src/assets 는 null
 *  - importKey : src/assets 파일은 스토리에서 import.meta.glob 으로 해석할 키 ("../../assets/a.jpg")
 *
 * 사용: pnpm generate-assets  (= node scripts/generate-asset-inventory.js)
 */

import { readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, extname, basename, dirname } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const OUT = join(ROOT, 'src', 'data', 'assetInventory.js');
const ROOTS = ['src/assets', 'public'];
const SKIP = new Set(['storybook', '.DS_Store', 'node_modules']);

const KIND = {
  image: ['.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg', '.avif'],
  video: ['.mp4', '.webm', '.mov'],
  audio: ['.mp3', '.wav', '.ogg', '.m4a'],
  font: ['.woff', '.woff2', '.ttf', '.otf'],
  model: ['.glb', '.gltf'],
};

function kindOf(ext) {
  for (const [k, exts] of Object.entries(KIND)) if (exts.includes(ext)) return k;
  return 'other';
}

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith('.') || SKIP.has(entry)) continue;
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) out.push(...walk(full));
    else out.push({ full, bytes: st.size });
  }
  return out;
}

const items = [];
for (const root of ROOTS) {
  const abs = join(ROOT, root);
  if (!existsSync(abs)) continue;
  for (const { full, bytes } of walk(abs)) {
    const rel = relative(ROOT, full);
    const inRoot = relative(abs, full);
    const ext = extname(full).toLowerCase();
    items.push({
      path: rel,
      root,
      folder: dirname(inRoot) === '.' ? '' : dirname(inRoot),
      name: basename(full),
      ext,
      kind: kindOf(ext),
      bytes,
      url: root === 'public' ? `/${inRoot}` : null,
      importKey: root === 'src/assets' ? `../../assets/${inRoot}` : null,
    });
  }
}

items.sort((a, b) => a.path.localeCompare(b.path));

const summary = {};
for (const it of items) {
  const key = `${it.root}/${it.folder || '(root)'}`;
  summary[key] ??= { files: 0, bytes: 0, image: 0, video: 0, audio: 0, font: 0, model: 0, other: 0 };
  summary[key].files += 1;
  summary[key].bytes += it.bytes;
  summary[key][it.kind] += 1;
}

writeFileSync(
  OUT,
  `/* eslint-disable */\n/**\n * Auto-generated by scripts/generate-asset-inventory.js\n * 수동 편집 금지. 재생성: pnpm generate-assets\n */\nexport default ${JSON.stringify({ generatedAt: new Date().toISOString(), summary, items }, null, 2)};\n`
);

console.log(`✓ wrote ${relative(ROOT, OUT)}`);
console.log(`  files: ${items.length}, folders: ${Object.keys(summary).length}`);
