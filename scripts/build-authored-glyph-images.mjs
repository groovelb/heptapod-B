#!/usr/bin/env node
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { ARCHIVE_FAMILY_SYMBOLS, ARCHIVE_TIMELINE_SYMBOL } from '../src/data/archiveFamilySymbols.js';
import { getArchiveArchetypeSymbol } from '../src/data/archiveArchetypeSymbols.js';
import { ARCHETYPE_CATALOG } from '../src/data/heptapodArchetypeCatalog.js';
import { renderGlyphImage } from '../src/lib/glyphImages/rasterize.js';
import { canonicalModelJson, glyphModelHash, GLYPH_IMAGE_SIZES, GLYPH_IMAGE_VERSION } from '../src/lib/glyphImages/contract.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const publicPath = `/glyph-symbols/v${GLYPH_IMAGE_VERSION}`;
const directory = resolve(root, `public${publicPath}`);
await mkdir(directory, { recursive: true });
const inputs = [
  ...Object.entries(ARCHIVE_FAMILY_SYMBOLS).map(([id, symbol]) => ({ id: `family-${id}`, model: symbol.model })),
  { id: 'timeline', model: ARCHIVE_TIMELINE_SYMBOL.model_data },
  ...Object.keys(ARCHETYPE_CATALOG).map((key) => ({ id: `type-${key}`, model: getArchiveArchetypeSymbol(key).model })),
];
const manifest = { rendererVersion: GLYPH_IMAGE_VERSION, symbols: {}, images: {} };
const modelKeys = {};
const measurements = [];
for (const { id, model } of inputs) {
  const hash = await glyphModelHash(model);
  modelKeys[canonicalModelJson(model)] = hash;
  manifest.symbols[id] = hash;
  if (manifest.images[hash]) continue;
  const variants = {};
  for (const size of GLYPH_IMAGE_SIZES) {
    const started = performance.now();
    const image = await renderGlyphImage(model, { size });
    const filename = `${hash}-${size}-1c2226.png`;
    await writeFile(resolve(directory, filename), image.bytes);
    variants[size] = { src: `${publicPath}/${filename}`, width: image.width, height: image.height,
      mimeType: image.mimeType, checksum: image.checksum };
    measurements.push({ id, size, bytes: image.bytes.length, milliseconds: Math.round(performance.now() - started) });
  }
  manifest.images[hash] = variants;
}
await writeFile(resolve(directory, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(resolve(root, 'src/lib/glyphImages/authoredManifest.js'),
  '// Generated by scripts/build-authored-glyph-images.mjs. Do not edit manually.\n'
  + `export const AUTHORED_GLYPH_IMAGES = ${JSON.stringify(manifest.images, null, 2)};\n`
  + `const MODEL_HASHES = ${JSON.stringify(modelKeys, null, 2)};\n`
  + 'export const AUTHORED_GLYPH_IMAGES_BY_MODEL = Object.fromEntries(\n'
  + '  Object.entries(MODEL_HASHES).map(([model, hash]) => [model, AUTHORED_GLYPH_IMAGES[hash]]),\n);\n');
const reportDirectory = resolve(root, 'output/mobile-static-glyphs');
await mkdir(reportDirectory, { recursive: true });
await writeFile(resolve(reportDirectory, 'authored-generation.json'), `${JSON.stringify(measurements, null, 2)}\n`);
console.log(JSON.stringify({ symbols: inputs.length, uniqueModels: Object.keys(manifest.images).length,
  images: measurements.length, bytes: measurements.reduce((sum, item) => sum + item.bytes, 0),
  milliseconds: measurements.reduce((sum, item) => sum + item.milliseconds, 0), measurements }, null, 2));
